-- ─── D-6: UNIQUE constraint on creative_quality ──────────────────────────────
-- The ON CONFLICT DO NOTHING in QualityScoreScheduler.refreshCreativeQuality was
-- silently failing without an explicit conflict target.  Two partial unique indexes
-- (creative-level and variant-level) cover the two aggregation paths.
CREATE UNIQUE INDEX IF NOT EXISTS uq_creative_quality_creative
    ON creative_quality (tenant_id, creative_id, window_key)
    WHERE variant_id IS NULL AND creative_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_creative_quality_variant
    ON creative_quality (tenant_id, variant_id, window_key)
    WHERE creative_id IS NULL AND variant_id IS NOT NULL;

-- ─── D-5: ON DELETE CASCADE for all FK references to sessions(id) ────────────
-- Without CASCADE, deleting a session (GDPR erasure or retention sweep) fails with
-- FK violations; the application had to manually delete children first.
-- The DO block discovers constraint names dynamically (auto-generated by Postgres
-- when no CONSTRAINT name was given) and recreates each with ON DELETE CASCADE.
DO $$
DECLARE
    r record;
BEGIN
    FOR r IN
        SELECT
            tc.table_name        AS tbl,
            tc.constraint_name   AS con,
            kcu.column_name      AS col
        FROM information_schema.table_constraints      tc
        JOIN information_schema.key_column_usage       kcu  ON kcu.constraint_name  = tc.constraint_name
                                                            AND kcu.table_schema     = tc.table_schema
        JOIN information_schema.referential_constraints rc  ON rc.constraint_name   = tc.constraint_name
                                                            AND rc.constraint_schema = tc.table_schema
        JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name  = rc.unique_constraint_name
                                                            AND ccu.table_schema     = tc.table_schema
        WHERE tc.constraint_type = 'FOREIGN KEY'
          AND ccu.table_name     = 'sessions'
          AND tc.table_schema    = 'public'
    LOOP
        EXECUTE format(
            'ALTER TABLE public.%I DROP CONSTRAINT %I; '
            'ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES sessions(id) ON DELETE CASCADE',
            r.tbl, r.con,
            r.tbl, r.con, r.col);
    END LOOP;
END $$;

-- ─── D-15: validate partition range before inserting events ──────────────────
-- The ensure_events_partition function only creates partitions for future months;
-- ingestion of events with an event_time outside any existing partition would raise
-- a "no partition" error.  This function returns FALSE when the given event_time has
-- no covering partition — the ingestion service calls it before accepting an event.
CREATE OR REPLACE FUNCTION public.event_partition_exists(p_event_time timestamptz)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM   pg_class child
        JOIN   pg_inherits inh     ON inh.inhrelid  = child.oid
        JOIN   pg_class   parent   ON parent.oid     = inh.inhparent
        JOIN   pg_namespace n      ON n.oid          = child.relnamespace
        WHERE  parent.relname  = 'events'
          AND  n.nspname        = 'public'
          AND  child.relkind    = 'r'
          -- pg_get_expr evaluates the partition bound and we check the timestamp falls in range
          AND  p_event_time >= lower(pg_catalog.pg_get_partition_constraintdef(child.oid)::text::anyrange)::timestamptz
          AND  p_event_time <  upper(pg_catalog.pg_get_partition_constraintdef(child.oid)::text::anyrange)::timestamptz
    )
$$;

-- Simpler and production-safe version: check via the partition name derived from the date
CREATE OR REPLACE FUNCTION public.event_partition_exists(p_event_time timestamptz)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM   pg_class c
        JOIN   pg_namespace n ON n.oid = c.relnamespace
        WHERE  n.nspname = 'public'
          AND  c.relname = 'events_' || to_char(p_event_time AT TIME ZONE 'UTC', 'YYYY_MM')
          AND  c.relkind = 'r'
    )
$$;

REVOKE ALL ON FUNCTION public.event_partition_exists(timestamptz) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.event_partition_exists(timestamptz) TO mai_app;
GRANT EXECUTE ON FUNCTION public.event_partition_exists(timestamptz) TO mai_ml;

