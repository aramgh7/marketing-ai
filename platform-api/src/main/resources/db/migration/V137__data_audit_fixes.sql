-- ─── D-23: DailyBriefScheduler deduplication ─────────────────────────────────
-- Tracks which (tenant_id, brief_date) pairs have already had a daily brief sent,
-- preventing double-delivery when the scheduler restarts or runs twice.
CREATE TABLE IF NOT EXISTS daily_brief_log (
    id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id   UUID        NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    brief_date  DATE        NOT NULL,
    sent_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    channel     VARCHAR(20) NOT NULL DEFAULT 'ALERT', -- ALERT | EMAIL | BOTH
    CONSTRAINT uq_daily_brief_tenant_date UNIQUE (tenant_id, brief_date)
);

CREATE INDEX IF NOT EXISTS idx_daily_brief_log_tenant
    ON daily_brief_log(tenant_id, brief_date DESC);

ALTER TABLE daily_brief_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE daily_brief_log FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON daily_brief_log
    USING (tenant_id = NULLIF(current_setting('app.current_tenant', true), '')::uuid
           OR current_setting('app.rls_bypass', true) = 'on');

GRANT SELECT, INSERT, DELETE ON daily_brief_log TO mai_app;

