package com.marketingai.scheduler;

import com.marketingai.service.MlServiceClient;
import com.marketingai.util.Jsonb;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * Blocked-creative recovery (roadmap 9-9; arch §16.7): a graveyard entry with failure_mode =
 * 'blocked_by_meta' and no recovery brief gets a Creator Brief generated by ML (/brief/generate) whose
 * product_info carries the phrases Meta rejected (analysis.blocked_phrases / analysis.reason) as an
 * explicit avoid-list; the brief is stored in creator_briefs and linked back. Every 6 h.
 */
@Slf4j
@Component
@RequiredArgsConstructor
public class BlockedCreativeRecoveryScheduler {

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private final JdbcTemplate jdbc;
    private final MlServiceClient mlClient;

    @Scheduled(fixedDelay = 6 * 3_600_000L, initialDelay = 900_000)
    public void recover() {
        List<Map<String, Object>> rows = jdbc.queryForList("""
                SELECT p.id, p.tenant_id, p.creative_id, p.analysis, c.title, c.type
                FROM creative_postmortems p
                LEFT JOIN creatives c ON c.id = p.creative_id
                WHERE p.failure_mode = 'blocked_by_meta' AND p.recovery_brief_id IS NULL
                ORDER BY p.created_at
                LIMIT 50
                """);
        for (Map<String, Object> row : rows) {
            UUID postmortemId = (UUID) row.get("id");
            UUID tenantId = (UUID) row.get("tenant_id");
            try {
                String avoid = avoidText(row.get("analysis"));
                String productInfo = "RECOVERY BRIEF for creative blocked by Meta review. AVOID these phrases/claims: "
                        + avoid + ". Keep every claim inside the approved-phrase pool.";
                Map<String, Object> req = Map.of(
                        "tenant_id", tenantId.toString(),
                        "creative_type", row.get("type") != null ? row.get("type") : "VIDEO",
                        "target_audience", "same audience as the blocked creative",
                        "product_info", productInfo,
                        "days", 90);
                @SuppressWarnings("unchecked")
                Map<String, Object> brief = mlClient.post("/brief/generate", req, Map.class);
                UUID briefId = jdbc.queryForObject("""
                        INSERT INTO creator_briefs (tenant_id, title, creative_type, target_audience, product_info)
                        VALUES (?, ?, ?, ?, ?)
                        RETURNING id
                        """, UUID.class, tenantId,
                        "Recovery: " + (row.get("title") != null ? row.get("title") : row.get("creative_id")),
                        String.valueOf(req.get("creative_type")),
                        String.valueOf(req.get("target_audience")),
                        productInfo + "\n\n" + (brief != null ? MAPPER.writeValueAsString(brief) : "{}"));
                jdbc.update("UPDATE creative_postmortems SET recovery_brief_id = ?, recovery_requested_at = now() WHERE id = ?",
                        briefId, postmortemId);
                log.info("BlockedCreativeRecovery: postmortem={} brief={}", postmortemId, briefId);
            } catch (Exception e) {
                log.warn("BlockedCreativeRecovery: postmortem {} skipped: {}", postmortemId, e.getMessage());
            }
        }
    }

    /** Phrases to avoid from the postmortem analysis: blocked_phrases[] or reason. */
    static String avoidText(Object analysisRaw) {
        try {
            String json = Jsonb.asString(analysisRaw);
            if (json == null) return "n/a";
            JsonNode a = MAPPER.readTree(json);
            List<String> parts = new ArrayList<>();
            for (JsonNode p : a.path("blocked_phrases")) parts.add(p.asText());
            if (a.hasNonNull("reason")) parts.add(a.get("reason").asText());
            if (a.hasNonNull("ad_review_feedback")) parts.add(a.get("ad_review_feedback").toString());
            return parts.isEmpty() ? "n/a" : String.join("; ", parts);
        } catch (Exception e) {
            return "n/a";
        }
    }
}
